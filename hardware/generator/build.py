def build_schematic():
    sch = schgen.Schematic(NAME, C.TITLE, C.REV, C.DATE, "Open hardware, CERN-OHL-P-2.0",
                           comments=("ESP32-S3 gateway for NIBE F-series heat pumps (MODBUS 40 port)",
                                     "Generated by hardware/generator/build.py - edit circuit.py, not this file"))
    for title, x1, y1, x2, y2 in BLOCKS:
        sch.box(x1, y1, x2, y2)
        sch.text(title, x1 + 2.54, y1 + 5.08, size=2.54)
    for text, x, y in NOTES:
        sch.text(text, x, y, size=1.27, bold=False)
    for ref, p in C.PARTS.items():
        sym, fp, value, lcsc, mpn = p["part"]
        props = {"Footprint": fp}
        if lcsc:
            props["LCSC"] = lcsc
        if mpn:
            props["MPN"] = mpn
        x, y, r = p["sch"]
        sch.part(sym, ref, value, x, y, p["nets"], r=r, props=props, dnp=p.get("dnp", False),
                 in_bom=not p.get("nobom", False))
    # ERC: mark nets that are fed by passive parts as driven
    for net, x, y in (("GND", 22.86, 124.46), ("+3V3", 220.98, 78.74), ("VBUCK", 137.16, 76.2)):
        sch.pwr_flag(net, x, y)
    sch.write(SCH)
    return sch


