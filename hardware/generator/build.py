def netlist():
    xml = os.path.join(KDIR, NAME + ".net.xml")
    run(["kicad-cli", "sch", "export", "netlist", "--format", "kicadxml", "-o", xml, SCH])
    root = ET.parse(xml).getroot()
    pin_net = {}
    for net in root.iter("net"):
        name = net.get("name")
        for node in net.iter("node"):
            pin_net[(node.get("ref"), node.get("pin"))] = name
    os.remove(xml)
    return pin_net


def plain(n):
    return n[1:] if n.startswith("/") else n


def verify_netlist(sch, pin_net):
    errors = []
    for (ref, pin), want in sch.expected.items():
        if ref.startswith("#"):
            continue
        got = pin_net.get((ref, pin))
        if want is None:
            if got and not got.startswith("unconnected-"):
                errors.append("%s.%s should be unconnected but is on %s" % (ref, pin, got))
            continue
        if got is None or plain(got) != want:
            errors.append("%s.%s expected %s got %s" % (ref, pin, want, got))
    # every net must have at least two pins
    members = {}
    for (ref, pin), n in pin_net.items():
        if not n.startswith("unconnected-") and not ref.startswith("#"):
            members.setdefault(n, []).append("%s.%s" % (ref, pin))
    for n, m in members.items():
        if len(m) < 2:
            errors.append("net %s has a single pin %s" % (n, m))
    return errors, members


def erc():
    out = os.path.join(KDIR, "erc.json")
    run(["kicad-cli", "sch", "erc", "--format", "json", "--severity-all", "-o", out, SCH], check=False)
    data = json.load(open(out))
    os.remove(out)
    issues = []
    for sheet in data.get("sheets", []):
        for v in sheet.get("violations", []):
            items = "; ".join(i.get("description", "") for i in v.get("items", []))
            issues.append((v["severity"], v["type"], v["description"], items))
    return issues


def step_sch():
    os.makedirs(KDIR, exist_ok=True)
    write_project()
    sch = build_schematic()
    pin_net = netlist()
    errors, members = verify_netlist(sch, pin_net)
    print("netlist: %d nets" % len(members))
    for e in errors:
        print("  NETLIST ERROR:", e)
    issues = erc()
    for sev, typ, desc, items in issues:
        print("  ERC %s %s: %s | %s" % (sev, typ, desc, items[:160]))
    print("ERC: %d issues (%d errors)" % (len(issues), sum(1 for i in issues if i[0] == "error")))
    if errors:
        raise SystemExit("netlist does not match circuit.py")
    with open(os.path.join(KDIR, ".pin_nets.json"), "w") as f:
        json.dump({"%s|%s" % k: v for k, v in pin_net.items()}, f, indent=0)
    return pin_net


